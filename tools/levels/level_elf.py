#!/usr/bin/env python3
"""Level-build helpers for tools/levels/level_build.sh (task #2457, NOTE #13098 row L4).

    level_elf.py undef  <LNN.ld> <nm -u names> <nm --defined-only names> <out.ld> [<boot names .ld>]
    level_elf.py check  <LNN.elf> <extracted level dir> <blob out dir> <LNN.yaml> [--expect <tsv> --version us2 --program NN]
    level_elf.py cobj   <fn.o> <function> <size>

Our own code; runs under a bare `python3 -I` (ee-build or host). No YAML or ELF
library.

undef: every symbol the level objects leave undefined (referenced in one
  object and defined in none of them) must be either a core
  name already assigned in LNN.ld (core_externs.txt) or ADDRESS-NAMED
  (`D_001A8CC8`, `D_L24_0025B420`, `func_...`, `jtbl_...`), in which case its
  value is the address in its name: the split's own convention, as the boot's
  undefined_syms_auto.txt. Anything else is a hard failure, listed. Writes one
  `name = 0x...;` per address-named symbol and prints the classes with members.
  With a boot names script (task #2516: symbol_addrs/LNN_boot_names.txt, comments
  stripped), a name it assigns (`name = 0x...;` or the alias `func_LNN_X = boot;`)
  is resolved there and NOT written to out.ld, so a placed function's level
  identity resolves through its alias, not through the address in its name.

check: reads the linked ELF only (section headers, the PT_LOAD, e_entry):
  * each of the 7 program sections, by ELF name, in program order: its
    sh_addr / sh_size / sh_type, and its bytes taken from the PT_LOAD file
    image at its address (a NOBITS .bss inside the one PT_LOAD is file-backed
    by ld, so its bytes are what ld wrote, not synthesised here);
  * writes the 7 blobs to <blob out dir>/<stem>.bin and compares each with the
    extracted <stem>.bin byte by byte; prints `cmp <stem> 0` or the differing
    count and the first differing address, NAMING the section;
  * compares dest/size/type with the extracted manifest and e_entry with the
    manifest's entry;
  * repacks the archive form ({dest,size,type,entry} + bytes per section, the
    format of tools/levels/extract_levels.py) FROM THE ELF ALONE (type =
    sh_type, entry = e_entry) and prints its sha1 / size / entry, compared
    with the program sha1 recorded in LNN.yaml's header and, with --expect,
    with a `version program sha1 size entry` TSV row (OpenRAC programs.tsv).
  Exit 0 only if every comparison holds.
"""
import hashlib
import json
import os
import re
import struct
import sys

# program order: (blob stem, ELF section name) -- tools/levels/extract_levels.py SECTIONS
SECTIONS = [("lit", ".lit"), ("bss", ".bss"), ("data", ".data"), ("vtbl", "lvl.vtbl"),
            ("camvtbl", "lvl.camvtbl"), ("sndvtbl", "lvl.sndvtbl"), ("text", ".text")]
PT_LOAD = 1
ADDR_NAME = re.compile(r"^(?:func|D|jtbl|B|RO|T|FLT|DBL|STR|PSTR)_(?:L\d\d_)?([0-9A-F]{1,8})$")


def cmd_undef(ld_path, nm_path, def_path, out_path, boot_ld=None):
    assigned = set(re.findall(r"^([A-Za-z_][\w.$]*) = ABSOLUTE\(", open(ld_path).read(), re.M))
    boot = set(re.findall(r"^\s*([A-Za-z_][\w.$]*) = [^;]+;", open(boot_ld).read(), re.M)) if boot_ld else set()
    bval, balias, cval = {}, {}, {}
    if boot_ld:
        bt = open(boot_ld).read()
        bval = {n: int(v, 16) for n, v in re.findall(r"^\s*([A-Za-z_][\w.$]*) = 0x([0-9A-Fa-f]+);", bt, re.M)}
        balias = dict(re.findall(r"^\s*([A-Za-z_][\w.$]*) = ([A-Za-z_][\w.$]*);", bt, re.M))
        cval = {n: int(v, 16) for n, v in re.findall(r"^([A-Za-z_][\w.$]*) = ABSOLUTE\(0x([0-9A-Fa-f]+)\);", open(ld_path).read(), re.M)}
    defined = {l.split()[-1] for l in open(def_path) if l.strip()}
    refs = {l.split()[-1] for l in open(nm_path) if l.strip()}
    names = sorted(refs - defined)
    print("undef: %d names referenced across objects, %d of them defined in another level object, %d undefined"
          % (len(refs), len(refs & defined), len(names)))
    core, addr, bad, viaboot = [], [], [], []
    for n in names:
        if n in assigned:
            core.append(n)
            continue
        if n in boot:
            viaboot.append(n)
            continue
        m = ADDR_NAME.match(n)
        if m:
            addr.append((n, int(m.group(1), 16)))
        else:
            bad.append(n)
    with open(out_path, "w") as f:
        f.write("/* GENERATED by tools/levels/level_elf.py undef: address-named undefined symbols,\n"
                "   valued at the address in their name. */\n")
        for n, a in addr:
            f.write("%s = 0x%08X;\n" % (n, a))
    lo = 0x1A7C80
    lvl = [n for n, a in addr if "_L" in n]
    below = [n for n, a in addr if a < lo and "_L" not in n]
    above = [n for n, a in addr if a >= lo and "_L" not in n]
    print("undef: %d undefined names: %d core (LNN.ld), %d address-named [%d level-prefixed, %d below 0x%X, %d other]"
          % (len(names), len(core), len(addr), len(lvl), len(below), lo, len(above)))
    if boot_ld:
        print("undef: %d resolved by the boot names script %s (placed functions' aliases): %s"
              % (len(viaboot), boot_ld, " ".join(viaboot)))
    print("undef: level-prefixed: %s" % " ".join(lvl))
    print("undef: address-named at/above 0x%X, unprefixed: %s" % (lo, " ".join(above)))
    # a name the LEVEL objects reference and the boot script resolves must keep
    # what the level asm means by it: an address-named one the address in its
    # name (aliases followed), a core one its core value
    clash, nchk = [], 0
    for n in sorted(viaboot + [c for c in core if c in bval]):
        v = bval.get(n, bval.get(balias.get(n)))
        m = ADDR_NAME.match(n)
        if m:
            nchk += 1
            if v != int(m.group(1), 16):
                clash.append("%s=%s (address in name 0x%s)" % (n, "0x%08X" % v if v is not None else "?", m.group(1)))
        if n in cval:
            nchk += 1
            if v != cval[n]:
                clash.append("%s=%s (core 0x%08X)" % (n, "0x%08X" % v if v is not None else "?", cval[n]))
    if boot_ld:
        print("undef: boot names script: %d level references it resolves checked (address in name / core value), %d differ: %s"
              % (nchk, len(clash), " ".join(clash)))
    if bad:
        print("undef: UNRESOLVED %d: %s" % (len(bad), " ".join(bad)))
        return 1
    return 1 if clash else 0


def read_elf(path):
    b = open(path, "rb").read()
    if b[:4] != b"\x7fELF" or b[4] != 1 or b[5] != 1:
        sys.exit("check: %s is not an ELF32 LE" % path)
    entry, phoff, shoff = struct.unpack_from("<III", b, 0x18)
    phentsize, phnum, shentsize, shnum, shstrndx = struct.unpack_from("<HHHHH", b, 0x2A)
    phs = [struct.unpack_from("<8I", b, phoff + i * phentsize) for i in range(phnum)]
    shs = [struct.unpack_from("<10I", b, shoff + i * shentsize) for i in range(shnum)]
    so = shs[shstrndx][4]
    sec = {}
    for s in shs:
        nm = b[so + s[0]:b.index(b"\0", so + s[0])].decode()
        sec[nm] = s
    return b, entry, phs, sec


def cmd_check(elf_path, ext_dir, out_dir, yaml_path, expect=None, version="us2", program=None):
    b, entry, phs, sec = read_elf(elf_path)
    man = json.load(open(os.path.join(ext_dir, "manifest.json")))
    loads = [p for p in phs if p[0] == PT_LOAD]
    ok = True
    print("check: %s  PT_LOAD count %d" % (elf_path, len(loads)))
    if len(loads) != 1:
        print("check: FAIL expected exactly one PT_LOAD, got %d" % len(loads))
        ok = False
    _, p_off, p_vaddr, _, p_filesz, p_memsz, _, _ = loads[0]
    os.makedirs(out_dir, exist_ok=True)
    recs = []
    for (stem, ename), ms in zip(SECTIONS, man["sections"]):
        s = sec.get(ename)
        if s is None:
            print("check: FAIL section %s missing from the ELF" % ename)
            ok = False
            continue
        typ, addr, size = s[1], s[3], s[5]
        if not (p_vaddr <= addr and addr + size <= p_vaddr + p_filesz):
            print("check: FAIL %s 0x%X+0x%X is not file-backed by the PT_LOAD" % (ename, addr, size))
            ok = False
            continue
        body = b[p_off + addr - p_vaddr:p_off + addr - p_vaddr + size]
        open(os.path.join(out_dir, stem + ".bin"), "wb").write(body)
        ref = open(os.path.join(ext_dir, ms["file"]), "rb").read()
        mdest, msize, mtype = int(ms["dest"], 16), ms["size"], ms["type"]
        hdr = "dest %s size %s type %s" % (
            "ok" if addr == mdest else "0x%X!=0x%X" % (addr, mdest),
            "ok" if size == msize else "0x%X!=0x%X" % (size, msize),
            "ok" if typ == mtype else "%d!=%d" % (typ, mtype))
        n = min(len(body), len(ref))
        diff = [i for i in range(n) if body[i] != ref[i]] + list(range(n, max(len(body), len(ref))))
        first = (" first at 0x%08X" % (mdest + diff[0])) if diff else ""
        print("check: cmp %-8s %-12s %d differing bytes of %d%s  (built 0x%08X..0x%08X; %s)"
              % (stem, ename, len(diff), len(ref), first, addr, addr + size, hdr))
        if diff or addr != mdest or size != msize or typ != mtype:
            ok = False
        recs.append((addr, size, typ, body))
    want_entry = int(man["entry"], 16)
    print("check: entry 0x%08X (manifest 0x%08X) %s" % (entry, want_entry, "OK" if entry == want_entry else "DIFFERS"))
    ok &= entry == want_entry
    prog = b"".join(struct.pack("<4I", d, n, t, entry) + body for d, n, t, body in recs)
    h = hashlib.sha1(prog).hexdigest()
    ysha = re.search(r"program sha1 ([0-9a-f]{40})", open(yaml_path).read()).group(1)
    print("check: repacked sha1 %s size %d entry %08X; LNN.yaml header %s %s"
          % (h, len(prog), entry, ysha, "EQUAL" if h == ysha else "DIFFERS"))
    ok &= h == ysha
    if expect:
        row = None
        for line in open(expect):
            p = line.rstrip("\n").split("\t")
            if len(p) >= 5 and p[0] == version and p[1] == program:
                row = p
        if row is None:
            print("check: FAIL no %s %s row in %s" % (version, program, expect))
            ok = False
        else:
            same = (row[2], int(row[3]), row[4].upper()) == (h, len(prog), "%08X" % entry)
            print("check: expect %s %s: %s %s %s %s" % (version, program, row[2], row[3], row[4], "EQUAL" if same else "DIFFERS"))
            ok &= same
    print("check: %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def cmd_cobj(obj_path, fn, size):
    """A C function's object before the link (task #2495): its only allocated,
    non-empty section is .text, of exactly the cut block's size, and the one
    global it defines there is <fn> at offset 0. Anything else (.rodata,
    .data, .sdata, a jump table, a second function) would land in /DISCARD/ or
    shift the program silently, so it fails here instead."""
    size = int(size, 0)
    b = open(obj_path, "rb").read()
    if b[:4] != b"\x7fELF" or b[4] != 1 or b[5] != 1 or struct.unpack_from("<H", b, 0x10)[0] != 1:
        print("cobj: FAIL %s is not an ELF32 LE relocatable" % obj_path)
        return 1
    shoff, = struct.unpack_from("<I", b, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", b, 0x2E)
    shs = [struct.unpack_from("<10I", b, shoff + i * shentsize) for i in range(shnum)]
    so = shs[shstrndx][4]
    nm = lambda off, base: b[base + off:b.index(b"\0", base + off)].decode()
    names = [nm(s[0], so) for s in shs]
    ok = True
    # SHT_MIPS_REGINFO / SHT_MIPS_ABIFLAGS are allocated MIPS metadata every
    # object (asm ones too) carries; LNN.ld discards them, and they are no code
    meta = (0x70000006, 0x7000002A)
    alloc = [(names[i], s[5]) for i, s in enumerate(shs) if s[2] & 0x2 and s[5] > 0 and s[1] not in meta]
    if [n for n, _ in alloc] != [".text"]:
        print("cobj: FAIL %s: allocated non-empty sections %s (want only .text)" % (obj_path, alloc))
        ok = False
    ti = names.index(".text") if ".text" in names else -1
    tsize = shs[ti][5] if ti >= 0 else -1
    if tsize != size:
        print("cobj: FAIL %s: .text is 0x%X bytes, the cut block is 0x%X" % (obj_path, tsize, size))
        ok = False
    st = next(s for s in shs if s[1] == 2)
    strs = shs[st[6]][4]
    glob = []
    for i in range(st[5] // 16):
        n, v, sz, info, oth, shn = struct.unpack_from("<IIIBBH", b, st[4] + 16 * i)
        if info >> 4 == 1 and shn == ti:
            glob.append((nm(n, strs), v))
    if glob != [(fn, 0)]:
        print("cobj: FAIL %s: globals defined in .text %s (want exactly [(%r, 0)])" % (obj_path, glob, fn))
        ok = False
    nrel = sum(s[5] // 8 for i, s in enumerate(shs) if s[1] == 9 and s[7] == ti)
    print("cobj: %s %s: .text 0x%X bytes (cut block 0x%X), globals %s, %d relocations, allocated %s"
          % ("PASS" if ok else "FAIL", obj_path, tsize, size, glob, nrel, alloc))
    return 0 if ok else 1


