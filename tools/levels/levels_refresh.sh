#!/bin/bash
# LEVELS REFRESH: bring every level's committed boot-placement map up to date
# with the boot C set of THIS tree (task #2525, RULING #13219).
#
#   bash tools/levels/levels_refresh.sh          # refresh; exit 0 = nothing changed, 1 = changed
#   bash tools/levels/levels_refresh.sh --gate   # refresh, then level_gate.sh for each level
#
# Why: LNN_boot_c.tsv, LNN_boot_names.txt and LNN.ld are a function of the BOOT
# C set (gen_boot_names.py reads the boot build's objects and ELF). Any boot
# landing that turns a function a level carries into C, or changes one, makes
# them stale, and the boot landing gate does not run level gates (validator
# #2520 point (d)).
#
# Steps:
#   1. bash tools/levels/boot_objects.sh: fresh sectioned boot objects for this
#      tree (it runs the boot build first if tools/ee/.gate_landing/usa/
#      built_tree.txt does not name this worktree's tree; freshness is the
#      WHOLE tree, so any uncommitted edit anywhere costs a boot build).
#   2. For EVERY level with going-decompiled/levels/usa/LNN/config/LNN_boot_c.tsv:
#        python3 -I tools/levels/gen_boot_names.py names --level NN
#        python3 -I tools/levels/gen_ld.py going-decompiled/levels/usa/LNN/config/LNN.yaml
#   3. Compares every file under going-decompiled/levels/usa/LNN/ (tracked or
#      new, .gitignore honoured) before and after, and prints one
#      `CHANGED <path>: <why>` line per file that differs, then the added and
#      removed rows of a changed LNN_boot_c.tsv (the PLACED member delta).
#   --gate: then `bash tools/levels/level_gate.sh NN` for each level; its
#      `#### level_gate LNN: PASS` line is required. A refresh that changed
#      files leaves them uncommitted, so the gate's TREE row FAILs until they
#      are committed - by design: a PASS is about HEAD.
#
# Exit: 0 nothing changed (and, with --gate, every gate PASS); 1 something
# changed (gates PASS or not run); 2 a step failed (boot objects, generator,
# no level found); 3 --gate and a level gate did not PASS.
# Last line: `#### levels_refresh: FRESH|CHANGED (n)|ERROR|GATE FAIL ...`.
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT" || exit 2
GATE=0
for a in "$@"; do
  case "$a" in --gate) GATE=1;; *) echo "usage: levels_refresh.sh [--gate]"; exit 2;; esac
done
CTX=${EE_DOCKER_CONTEXT:-colima-ee-x86}
LROOT=going-decompiled/levels/usa
now() { date +%s.%N; }
secs() { awk -v a="$1" -v b="$2" 'BEGIN{printf "%.2f", b-a}'; }
T0=$(now)
err() { echo "levels_refresh: $*"; echo "#### levels_refresh: ERROR"; exit 2; }

# Levels: a directory LNN whose config holds LNN_boot_c.tsv (same NN both places).
LEVELS=()
for f in "$LROOT"/L*/config/L*_boot_c.tsv; do
  [ -f "$f" ] || continue
  d=$(basename "$(dirname "$(dirname "$f")")")
  [ "$(basename "$f")" = "${d}_boot_c.tsv" ] || continue
  LEVELS+=("${d#L}")
done
[ ${#LEVELS[@]} -gt 0 ] || err "no $LROOT/LNN/config/LNN_boot_c.tsv found (nothing to refresh is not a result)"
echo "levels_refresh: levels with boot rows: ${LEVELS[*]} (host $(uname -n), docker context $CTX, HEAD $(git rev-parse --short HEAD))"

# Snapshot every file the generators could touch, before.
SNAP=$(mktemp -d); trap 'rm -rf "$SNAP"' EXIT
list_files() { git ls-files -co --exclude-standard -- "$LROOT/L$1" | sort; }
for nn in "${LEVELS[@]}"; do
  list_files "$nn" > "$SNAP/L$nn.list"
  while IFS= read -r p; do mkdir -p "$SNAP/before/$(dirname "$p")"; cp -p "$p" "$SNAP/before/$p"; done < "$SNAP/L$nn.list"
done

t=$(now)
bash tools/levels/boot_objects.sh > "$SNAP/boot_objects.log" 2>&1; brc=$?
/usr/bin/grep -a -E '^boot_objects: (FRESH|STALE|REUSED|wall|boot build)|^#### boot_objects' "$SNAP/boot_objects.log" | sed 's/^/   /'
echo "levels_refresh: step boot_objects rc $brc, $(secs "$t" "$(now)") s"
/usr/bin/grep -a -q '^#### boot_objects: PASS' "$SNAP/boot_objects.log" || { tail -20 "$SNAP/boot_objects.log"; err "boot_objects.sh did not PASS"; }

for nn in "${LEVELS[@]}"; do
  t=$(now)
  python3 -I tools/levels/gen_boot_names.py names --level "$((10#$nn))" > "$SNAP/names$nn.log" 2>&1 \
    || { cat "$SNAP/names$nn.log"; err "gen_boot_names.py names --level $nn failed"; }
  /usr/bin/grep -a -E '^ *(PLACED|REFUSED) ' "$SNAP/names$nn.log" | sed "s/^ */   L$nn gen_boot_names: /"
  python3 -I tools/levels/gen_ld.py "$LROOT/L$nn/config/L$nn.yaml" > "$SNAP/ld$nn.log" 2>&1 \
    || { cat "$SNAP/ld$nn.log"; err "gen_ld.py L$nn.yaml failed"; }
  echo "levels_refresh: step L$nn names + gen_ld $(secs "$t" "$(now)") s"
done

why() {
  case "$1" in
    *_boot_c.tsv)      echo "placed set (func_LNN_<place> <boot name> <unit> <size>) regenerated from this tree's boot objects";;
    *_boot_names.txt)  echo "name map (values/aliases the placed code relocates against) regenerated from this tree's boot objects";;
    */linker_scripts/*.ld) echo "linker script regenerated by gen_ld.py from the placed set";;
    *) echo "NOT a generator output - investigate";;
  esac
}
N=0
for nn in "${LEVELS[@]}"; do
  list_files "$nn" > "$SNAP/L$nn.after"
  while IFS= read -r p; do
    if [ ! -f "$SNAP/before/$p" ]; then echo "CHANGED $p: new file; $(why "$p")"; N=$((N+1)); continue; fi
    cmp -s "$SNAP/before/$p" "$p" && continue
    echo "CHANGED $p: $(why "$p") (+$(diff "$SNAP/before/$p" "$p" | /usr/bin/grep -c '^>' || true)/-$(diff "$SNAP/before/$p" "$p" | /usr/bin/grep -c '^<' || true) lines)"
    N=$((N+1))
    case "$p" in *_boot_c.tsv)
      diff "$SNAP/before/$p" "$p" | sed -n 's/^> /   placed +  /p; s/^< /   placed -  /p';;
    esac
  done < "$SNAP/L$nn.after"
  comm -23 "$SNAP/L$nn.list" "$SNAP/L$nn.after" | while IFS= read -r p; do echo "CHANGED $p: deleted"; done
  N=$((N + $(comm -23 "$SNAP/L$nn.list" "$SNAP/L$nn.after" | wc -l)))
done
echo "levels_refresh: $N committed file(s) changed; refresh wall $(secs "$T0" "$(now)") s"

GF=0
if [ $GATE = 1 ]; then
  for nn in "${LEVELS[@]}"; do
    t=$(now)
    bash tools/levels/level_gate.sh "$nn" > "$SNAP/gate$nn.log" 2>&1; grc=$?
    v=$(/usr/bin/grep -a "^#### level_gate L$nn: " "$SNAP/gate$nn.log" | tail -1)
    /usr/bin/grep -a -E '^ *(FAIL|ok) +(TREE|FRESH|BOOTC|SECTIONS|ANCHOR)|^ *ledger ' "$SNAP/gate$nn.log" | sed 's/^ */   /'
    echo "levels_refresh: L$nn gate rc $grc '${v:-no verdict}' $(secs "$t" "$(now)") s"
    [ "$v" = "#### level_gate L$nn: PASS" ] && [ $grc = 0 ] || { GF=$((GF+1)); /usr/bin/grep -a -E '^ *FAIL ' "$SNAP/gate$nn.log" | sed 's/^ */   /'; }
  done
fi
echo "levels_refresh: wall $(secs "$T0" "$(now)") s (host $(uname -n), docker context $CTX)"
[ $GF = 0 ] || { echo "#### levels_refresh: GATE FAIL ($GF of ${#LEVELS[@]} levels)$([ $N -gt 0 ] && echo ", CHANGED ($N)")"; exit 3; }
[ $N = 0 ] || { echo "#### levels_refresh: CHANGED ($N)$([ $GATE = 1 ] && echo ', gates PASS')"; exit 1; }
echo "#### levels_refresh: FRESH$([ $GATE = 1 ] && echo ', gates PASS')"
exit 0
